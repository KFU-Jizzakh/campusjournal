<h2>Интероперабельность</h2>
<p>Журнал поддерживает протокол OAI-PMH (Open Archives Initiative Protocol for Metadata Harvesting), обеспечивающий возможность сбора метаданных внешними агрегаторами и репозиториями. Конечная точка OAI-PMH доступна по адресу <code>/oai</code> на сайте журнала.</p>

<h2>Самоархивирование авторами</h2>
<p>Авторы имеют право на самоархивирование (self-archiving) своих опубликованных работ без эмбарго-периода:</p>
<ul>
<li><strong>Препринт (до рецензирования):</strong> авторы могут размещать версию рукописи до рецензирования на персональных сайтах, в институциональных репозиториях и на серверах препринтов (например, arXiv, SocArXiv) в любое время.</li>
<li><strong>Постпринт (принятая рукопись после рецензирования):</strong> авторы могут размещать принятую к публикации версию (author accepted manuscript) в институциональных и тематических репозиториях с указанием информации о публикации в журнале «Global Campus RU».</li>
<li><strong>Финальная опубликованная версия (PDF издателя):</strong> авторы могут размещать финальную PDF-версию статьи в репозиториях и на личных сайтах при условии указания полной библиографической ссылки и гиперссылки на оригинальную публикацию на сайте журнала.</li>
</ul>

<h2>Идентификация и доступность</h2>
<ul>
<li>Журнал присваивает каждой статье уникальный идентификатор DOI (Digital Object Identifier) через Crossref, что гарантирует постоянную ссылку на публикацию независимо от изменений домена или платформы.</li>
<li>Метаданные статей депонируются в Crossref и доступны для академических поисковых систем (Google Scholar и др.) и библиографических баз данных.</li>
</ul>

